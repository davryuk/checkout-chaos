#!/usr/bin/env python3
"""Regenerate sprites.js (art/*.png as data URIs + foot anchors) and data.js (from data.json). Run: python3 build_sprites.py"""
import base64, json, os, struct
HERE = os.path.dirname(os.path.abspath(__file__)); ART = os.path.join(HERE, 'art')
MAP = {  # SPR key -> (file, frame size or None=height, anchor)
 'pl_recep':'player_recepcionista','pl_house':'player_housekeeping','pl_botones':'player_botones','pl_cocinero':'player_cocinero',
 'pl_mantenimiento':'player_mantenimiento','pl_conserje':'player_conserje_nocturno','pl_chef':'player_chef_ejecutivo',
 'pl_gerente':'player_gerente_general','pl_dueno':'player_dueno_hotel',
 'cos_recep_gala':'player_recepcionista_gala','cos_house_dorado':'player_housekeeping_delantal_dorado','cos_botones_gorra':'player_botones_gorra_roja',
 'cos_cocinero_gorro':'player_cocinero_gorro_alto','cos_mant_naranja':'player_mantenimiento_mameluco_naranja','cos_conserje_sobretodo':'player_conserje_sobretodo_largo',
 'e_apurado':'enemy_huesped_apurado','e_valija':'enemy_turista_valija','e_karen':'enemy_karen','e_queja':'enemy_queja_voladora',
 'e_despedida':'enemy_grupo_despedida','e_inspeccion':'boss_inspeccion','e_abogado':'elite_abogado','e_mucama':'enemy_mucama_fantasma','e_dueno':'boss_dueno_hotel',
 'food_caramelo':'food_caramelo','food_medialuna':'food_medialuna','food_club':'food_club_sandwich','food_pizza':'food_pizza','food_buffet':'food_buffet',
 'billete':'proj_billete','charco':'proj_charco_aceite','cuchillo':'proj_cuchillo','memo':'proj_memo',
 'pl_bartender':'player_bartender','pl_salvavidas':'player_salvavidas','pl_masajista':'player_masajista','pl_seguridad':'player_seguridad','pl_valet':'player_valet',
 'botella':'proj_botella','llama_piso':'fx_llama_piso','onda_silbato':'fx_onda_silbato','piedra_caliente':'proj_piedra_caliente','arco_baston':'fx_arco_baston','auto':'proj_auto',
 'evo_campana':'evo_campana_grande','evo_carrito':'evo_carrito_turbo','evo_valija':'evo_valija_dorada','evo_olla':'evo_olla','evo_nube':'evo_nube_verde','evo_llave':'evo_llave_maestra'}
FW = {'auto': 48, 'proj_limusina': 64, 'fx_latigazo_toalla': 48, 'fx_tsunami_ola': 64, 'fus_limusina_vip': 64}  # non-square frames (frame width)
def anchor(k, fs, fw=None):  # from art/README.md "Foot anchor"
    if k in ('e_inspeccion', 'e_dueno'): return [32, 59]
    if k in ('e_despedida', 'e_queja', 'e_mucama'): return [16, 30]
    if k.startswith(('pl_', 'cos_', 'e_')): return [16, 29]
    G = {'fx_barra_libre_fuego': [16, 24], 'fus_tren_vagon': [16, 26], 'fus_cinta_segmento': [16, 18], 'fus_campana_fija': [16, 28], 'fus_puerta': [16, 29], 'fus_mesa_bodas': [32, 34],
         'fx_charco_hielo': [16, 17], 'fx_arco_plumero': [4, 16], 'fx_latigazo_toalla': [0, 8]}
    if k in G: return G[k]
    if k == 'charco': return [16, 18]
    if k == 'llama_piso': return [16, 27]
    if k == 'auto': return [24, 12]
    return [fs // 2, fs // 2]
SKIP = ('preview', 'palette', 'roster')
used = set(MAP.values())
for f in sorted(os.listdir(ART)):   # auto-include every other PNG, key = filename
    n = f[:-4]
    if f.endswith('.png') and n not in used and not n.startswith(SKIP): MAP[n] = n
out, missing = {}, []
for k, f in MAP.items():
    p = os.path.join(ART, f + '.png')
    if not os.path.exists(p): missing.append(f); continue
    b = open(p, 'rb').read(); w, h = struct.unpack('>II', b[16:24]); fw = FW.get(k, 32 if k.startswith('ui_receta') else h)
    out[k] = {'src': 'data:image/png;base64,' + base64.b64encode(b).decode(), 'fs': h, 'fw': fw, 'frames': w // fw, 'anchor': anchor(k, h) if fw == h else [fw // 2, h // 2] if k not in ('fx_latigazo_toalla',) else [0, 8]}
open(os.path.join(HERE, 'sprites.js'), 'w').write('// GENERATED by build_sprites.py from art/*.png — do not edit\nwindow.SPRITE_SHEETS=' + json.dumps(out) + ';\n')
d = json.load(open(os.path.join(HERE, 'data.json')))
open(os.path.join(HERE, 'data.js'), 'w').write('// Fallback for file:// (fetch blocked). GENERATED from data.json by build_sprites.py — keep in sync\nwindow.GAME_DATA_FALLBACK=' + json.dumps(d, ensure_ascii=False) + ';\n')
print('sprites:', len(out), 'missing files:', missing)
