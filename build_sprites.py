#!/usr/bin/env python3
"""Regenerate sprites.js (art/*.png embedded as data URIs so file:// works). Run: python3 build_sprites.py"""
import base64, json, os, struct
ART = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'art')
MAP = {  # SPR key -> file
 'pl_recep':'player_recepcionista','pl_house':'player_housekeeping','pl_botones':'player_botones','pl_cocinero':'player_cocinero',
 'pl_mantenimiento':'player_mantenimiento','pl_conserje':'player_conserje_nocturno',
 'e_apurado':'enemy_huesped_apurado','e_valija':'enemy_turista_valija','e_karen':'enemy_karen','e_queja':'enemy_queja_voladora',
 'e_despedida':'enemy_grupo_despedida','e_inspeccion':'boss_inspeccion'}
out = {}
for k, f in MAP.items():
    b = open(os.path.join(ART, f + '.png'), 'rb').read()
    w, h = struct.unpack('>II', b[16:24])
    out[k] = {'src': 'data:image/png;base64,' + base64.b64encode(b).decode(), 'fs': h, 'frames': w // h}
open(os.path.join(os.path.dirname(ART), 'sprites.js'), 'w').write('// GENERATED by build_sprites.py from art/*.png — do not edit\nwindow.SPRITE_SHEETS=' + json.dumps(out) + ';\n')
print('sprites.js:', {k: (v['fs'], v['frames']) for k, v in out.items()})
